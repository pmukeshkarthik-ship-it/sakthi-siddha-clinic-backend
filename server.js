import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import mongoose from "mongoose";
import {connectDB} from "./config/db.js";
import authRoutes from "./routes/auth.js";
import appointmentRoutes from "./routes/appointments.js";
import publicRoutes from "./routes/public.js";
const app=express();
const PORT=process.env.PORT||5000;
if(!process.env.JWT_SECRET||process.env.JWT_SECRET.length<32) throw new Error("JWT_SECRET must be at least 32 characters.");
const origins=(process.env.CORS_ORIGIN||"http://localhost:5173").split(",").map(x=>x.trim());
app.use(helmet());
app.use(cors({origin(origin,cb){if(!origin||origins.includes(origin))return cb(null,true);cb(new Error("Origin not allowed by CORS"));}}));
app.use(express.json({limit:"20kb"}));
app.get("/api/health",(_req,res)=>res.json({status:"ok",database:mongoose.connection.readyState===1?"connected":"disconnected"}));
app.use("/api/auth",authRoutes);
app.use("/api/appointments",appointmentRoutes);
app.use("/api/public",publicRoutes);
app.use((_req,res)=>res.status(404).json({message:"Route not found."}));
app.use((err,_req,res,_next)=>{console.error(err);res.status(err.message==="Origin not allowed by CORS"?403:500).json({message:err.message==="Origin not allowed by CORS"?"Request origin is not allowed.":"An unexpected server error occurred."});});
connectDB().then(()=>app.listen(PORT,()=>console.log(`Clinic API running on ${PORT}`))).catch(err=>{console.error(err);process.exit(1);});
